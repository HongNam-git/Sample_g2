package bean;

public class School {
	
	private String cd;  //学校コード
	private String name;  // 学校の名
	
	
	//getter & setter
	public String getCd() {
		return cd;
	}
	public void setCd(String cd) {
		this.cd=cd;
		
	}
	
	
	public String getName() {
		return name;
	}
	public void setName(String name) {
		this.name=name;
	}

}
